/* 串口接收完成回调函数 */
void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t Size)
{
   if (huart->Instance == USART1)
   {

    BT_Parser_Process(uart1_rx_buffer, Size);

   	// HAL_UART_Transmit(&huart1, uart1_rx_buffer, Size, 0xffff);         // 将接收到的数据再发出
    
    HAL_UARTEx_ReceiveToIdle_DMA(&huart1, uart1_rx_buffer, BUFF_SIZE); // 接收完毕后重启串口DMA模式接收数据
   	__HAL_DMA_DISABLE_IT(&hdma_usart1_rx, DMA_IT_HT);		   	// 手动关闭DMA_IT_HT中断

   	memset(uart1_rx_buffer, 0, BUFF_SIZE);							// 清除接收缓存
   }
   else if (huart->Instance == UART4)
   {
    parseIMUData(uart4_rx_buffer, &imuData);

    HAL_UARTEx_ReceiveToIdle_DMA(&huart4, uart4_rx_buffer, BUFF_SIZE); // 接收完毕后重启串口DMA模式接收数据
   	__HAL_DMA_DISABLE_IT(&hdma_uart4_rx, DMA_IT_HT);		   	// 手动关闭DMA_IT_HT中断

   	memset(uart4_rx_buffer, 0, BUFF_SIZE);							// 清除接收缓存
   }
}	
